"""Functions that simulate dice rolls.

A dice function takes no arguments and returns a number from 1 to n
(inclusive), where n is the number of sides on the dice.

Fair dice produce each possible outcome with equal probability.
Two fair dice are already defined, four_sided and six_sided,
and are generated by the make_fair_dice function.

Test dice are deterministic: they always cycles through a fixed
sequence of values that are passed as arguments.
Test dice are generated by the make_test_dice function.
模拟掷骰子的函数。

一个骰子函数不接受任何参数，并返回一个从 1 到 n(包含 1 和 n)的数字,
其中 n 是骰子的面数。

公平骰子以相等的概率产生每一种可能的结果。
已经定义了两个公平骰子:four_sided 和 six_sided,
它们由 make_fair_dice 函数生成。

测试骰子是确定性的：它们总是循环遍历一组作为参数传入的固定数值序列。
测试骰子由 make_test_dice 函数生成。
"""

from random import randint

def make_fair_dice(sides):
    """Return a die that returns 1 to SIDES with equal chance.
    返回一个生成 1 到 SIDES 值的骰子，每个值概率相等"""
    assert type(sides) == int and sides >= 1, 'Illegal value for sides'
    def dice():
        return randint(1,sides)
    return dice

four_sided = make_fair_dice(4)
six_sided = make_fair_dice(6)

def make_test_dice(*outcomes):
    """Return a die that cycles deterministically through OUTCOMES.
        返回一个按 `OUTCOMES` 确定性地循环的骰子。
    >>> dice = make_test_dice(1, 2, 3)
    >>> dice()
    1
    >>> dice()
    2
    >>> dice()
    3
    >>> dice()
    1
    >>> dice()
    2

    This function uses Python syntax/techniques not yet covered in this course.
    The best way to understand it is by reading the documentation and examples.
    这个函数使用了本课程尚未涉及的 Python 语法/技巧。  
    理解它的最佳方式是阅读文档和示例。
    """
    assert len(outcomes) > 0, 'You must supply outcomes to make_test_dice'
    for o in outcomes:
        assert type(o) == int and o >= 1, 'Outcome is not a positive integer'
    index = len(outcomes) - 1
    def dice():
        nonlocal index
        index = (index + 1) % len(outcomes)
        return outcomes[index]
